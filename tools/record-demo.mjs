import { chromium } from '@playwright/test';
import { mkdir, rename } from 'node:fs/promises';
import assert from 'node:assert/strict';
const origin = process.env.APP_URL || 'http://127.0.0.1:4175';
const directory = '.private/demo-recording';
await mkdir(directory, { recursive: true });
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1366, height: 900 }, reducedMotion: 'reduce', recordVideo: { dir: directory, size: { width: 1366, height: 900 } } });
const page = await context.newPage();
const started = Date.now();
const at = async seconds => { const delay = started + seconds * 1000 - Date.now(); if (delay > 0) await new Promise(resolve => setTimeout(resolve, delay)); };
const pause = async () => { const button = page.getByRole('button', { name: 'Pause exercise' }); if (await button.count()) await button.click(); };
const advanceTo = async target => {
  await pause();
  const clock = (await page.locator('.clock-display').innerText()).split(':').map(Number);
  const minute = clock[0] * 60 + clock[1]; assert.ok(minute <= target, 'Demo advanced beyond its scripted decision');
  for (let i = minute; i < target; i++) await page.getByRole('button', { name: 'Advance one minute' }).click();
};
const select = id => page.locator(`#map-home-${id}`).click();
const send = async (id, unit, action, shelter) => {
  await select(id); await page.getByLabel('Response unit', { exact: true }).selectOption(unit);
  if (shelter) await page.getByLabel('Destination shelter').selectOption(shelter);
  await page.getByRole('button', { name: action, exact: true }).click();
  await page.getByRole('button', { name: 'Pause exercise' }).waitFor();
};
try {
  await page.goto(origin, { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Customize the scenario', exact: true }).click();
  await page.getByLabel('Where can?t people call for help?').selectOption('none');
  await at(5); await page.getByLabel('Where can?t people call for help?').selectOption('southeast');
  await at(8); await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByLabel('Vans to take people to shelter').selectOption('1'); await page.getByLabel('Vans to take people to shelter').selectOption('2');
  await at(13); await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await at(18); await page.getByRole('button', { name: 'Start exercise', exact: true }).click();
  await at(25); await send('H19', 'C1', 'Check home & run');
  await send('H09', 'V2', 'Check home & run');
  await at(30); await pause();
  await at(44); await advanceTo(8); await send('H19', 'V1', 'Send transport & run', 'A'); await send('H02', 'C1', 'Check home & run'); await pause();
  await at(68); await advanceTo(17); await send('H09', 'V2', 'Send transport & run', 'A');
  await at(72); await pause();
  await at(88); await advanceTo(24); await select('H19');
  await at(99); await send('H15', 'V1', 'Send transport & run', 'B'); await pause();
  await at(111); await advanceTo(28); await send('H02', 'C1', 'Deliver kit & run'); await pause();
  await at(122); await advanceTo(30); await send('H05', 'C1', 'Deliver kit & run'); await pause();
  await at(134); await advanceTo(35); await send('H12', 'C1', 'Deliver kit & run'); await pause();
  await at(145); await page.getByRole('button', { name: 'Exercise', exact: true }).click(); await page.getByRole('button', { name: 'Finish exercise', exact: true }).click();
  await page.getByRole('button', { name: 'Finish now', exact: true }).click();
  await page.getByRole('heading', { name: 'Results & analysis' }).waitFor();
  assert.equal(await page.getByText('6 of 6 needs resolved', { exact: true }).count(), 1);
  await at(157); await page.getByRole('tab', { name: 'Compare', exact: true }).click();
  await at(169); await page.getByRole('tab', { name: 'Homes', exact: true }).click();
  await at(177); await page.getByRole('tab', { name: 'Overview', exact: true }).click();
  await at(180);
  const video = page.video(); await page.close(); await context.close();
  const path = `${directory}/simpler-response-demo.webm`; await rename(await video.path(), path);
  console.log(JSON.stringify({ video: path, durationSeconds: 180, assisted: 6, timelyUrgent: 3, autoRunDemonstrated: true }));
} finally { await browser.close(); }
