import { chromium } from '@playwright/test';
import { mkdir, rename } from 'node:fs/promises';
import assert from 'node:assert/strict';
const origin = process.env.APP_URL || 'http://127.0.0.1:4175';
const directory = '.private/demo-recording';
await mkdir(directory, { recursive: true });
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1366, height: 900 }, reducedMotion: 'reduce', recordVideo: { dir: directory, size: { width: 1366, height: 900 } } });
const page = await context.newPage();
const started = Date.now();
const at = async seconds => { const delay = started + seconds * 1000 - Date.now(); if (delay > 0) await new Promise(resolve => setTimeout(resolve, delay)); };
const select = async id => { await page.locator(`.map-house[aria-label^="${id},"]`).click(); };
const step = async count => { for (let i = 0; i < count; i++) await page.getByRole('button', { name: 'Advance one minute' }).click(); };
const send = async (id, unit, action, shelter) => {
  await select(id); await page.getByLabel('Response unit', { exact: true }).selectOption(unit);
  if (shelter) await page.getByLabel('Destination shelter').selectOption(shelter);
  await page.getByRole('button', { name: new RegExp(`^${action}`) }).click();
};
try {
  await page.goto(origin, { waitUntil: 'networkidle' });
  await page.getByText('Prepared MiroFish behavior', { exact: true }).waitFor();
  await page.getByLabel('Scenario seed').fill('43');
  await page.getByLabel('Household communications').selectOption('none');
  await at(8);
  await page.getByRole('button', { name: 'Load default conditions' }).click();
  await page.getByText('Behavior provenance', { exact: true }).click();
  await page.locator('.provenance-drawer').scrollIntoViewIfNeeded();
  await at(18);
  await page.getByRole('button', { name: 'Create exercise', exact: true }).click();
  await at(25); await send('H19', 'C1', 'Assess');
  await at(33); await send('H09', 'V2', 'Assess');
  await at(44); await step(8);
  await send('H19', 'V1', 'Relocate', 'A');
  await send('H02', 'C1', 'Assess');
  await at(68); await step(9); await send('H09', 'V2', 'Relocate', 'A');
  await at(88); await step(7); await select('H19');
  await page.locator('.inspector').scrollIntoViewIfNeeded();
  await at(99); await send('H15', 'V1', 'Relocate', 'B');
  await at(111); await step(4); await send('H02', 'C1', 'Deliver kit');
  await at(122); await step(2); await send('H05', 'C1', 'Deliver kit');
  await at(134); await step(5); await send('H12', 'C1', 'Deliver kit');
  await at(145); await page.getByRole('button', { name: /Finish at minute 60/ }).click();
  await page.getByRole('button', { name: 'Finish exercise', exact: true }).click();
  await page.getByRole('heading', { name: 'Results & analysis' }).waitFor();
  assert.equal(await page.getByText('6/6', { exact: true }).count(), 1);
  await at(157); await page.getByText('Household timeline', { exact: true }).scrollIntoViewIfNeeded();
  await at(169); await page.getByText('Behavior provenance', { exact: true }).click();
  await page.locator('.provenance-drawer').scrollIntoViewIfNeeded();
  await at(177); await page.evaluate(() => scrollTo(0, 0));
  await at(180);
  const video = page.video(); await page.close(); await context.close();
  const path = `${directory}/catastrophe-response-demo.webm`;
  await rename(await video.path(), path);
  console.log(JSON.stringify({ video: path, durationSeconds: 180, assisted: 6, timelyUrgent: 3, recordedFromLiveApplication: true }));
} finally { await browser.close(); }
